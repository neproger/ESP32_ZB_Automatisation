let tsv = '# attribute\traw\tproperty\tvalue\n';
for (const row of golden) {
  const keys = Object.keys(row.out);
  if (keys.length === 0) {
    tsv += `${row.attr}\t${row.raw}\t-\t-\n`;
    continue;
  }
  for (const key of keys) tsv += `${row.attr}\t${row.raw}\t${key}\t${row.out[key]}\n`;
}
fs.writeFileSync(path.join(repo, 'crates/z2m-rs/tests/golden/snzb_01p_battery.tsv'), tsv);

// --- TS011F / tuyaOnOff: OnOff state is standard genOnOff; options stay partial.
const tsRaw = findDevice('ZMO-606-20A');
if (!tsRaw) { console.error('TS011F (ZMO-606-20A) not found'); process.exit(1); }
const tsFrag = (tsRaw.extend || []).find((e) => (e.fromZigbee || []).length >= 6);
if (!tsFrag) { console.error('tuyaOnOff fragment not found'); process.exit(1); }
const tsCall = calls.find((c) => c.result === tsFrag);
if (!tsCall || tsCall.helper !== 'tuya.tuyaOnOff') {
  console.error('expected tuya.tuyaOnOff, got', tsCall && tsCall.helper);
  process.exit(1);
}
const unsupported = ['indicatorMode', 'onOffCountdown', 'childLock'].filter((k) => tsCall.args && tsCall.args[k]);
const onoff = tsFrag.fromZigbee[0].convert;
const on = onoff(tsRaw, { data: { onOff: 1 } }, () => {}, {}, {});
const off = onoff(tsRaw, { data: { onOff: 0 } }, () => {}, {}, {});
if (on.state !== 'ON' || off.state !== 'OFF') {
  console.error('unexpected on_off ground truth', on, off);
  process.exit(1);
}

