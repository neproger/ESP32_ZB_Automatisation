// Fragment compiler: helper + options -> Rust fragment/profile + JS golden data.
// Dev tool. Run against the pinned ZHC package and device definitions directory.
const fs = require('node:fs');
const path = require('node:path');

const pkg = process.argv[2];
const devicesDir = process.argv[3];
const repo = path.resolve(__dirname, '../..');
if (!pkg || !devicesDir) {
  console.error('usage: node compile.cjs <zhc-pkg> <dist/devices>');
  process.exit(2);
}

const calls = [];
const stack = [];
function clean(v, depth = 0) {
  if (depth > 2) return '...';
  if (typeof v === 'function') return '[fn]';
  if (Array.isArray(v)) return v.slice(0, 8).map((x) => clean(x, depth + 1));
  if (v && typeof v === 'object') {
    const out = {};
    for (const k of Object.keys(v).slice(0, 16)) out[k] = clean(v[k], depth + 1);
    return out;
  }
  return v;
}
function wrap(obj, ns) {
  for (const key of Object.keys(obj)) {
    const fn = obj[key];
    if (typeof fn !== 'function') continue;
    obj[key] = function (...args) {
      const record = { helper: ns + '.' + key, args: clean(args.length === 1 ? args[0] : args), children: [] };
      calls.push(record);
      if (stack.length) stack[stack.length - 1].children.push(record);
      stack.push(record);
      try {
        const result = fn.apply(this, args);
        record.result = result;
        return result;
      } finally {
        stack.pop();
      }
    };
  }
}
wrap(require(path.join(pkg, 'dist/lib/tuya')).modernExtend, 'tuya');
wrap(require(path.join(pkg, 'dist/lib/modernExtend')), 'modernExtend');

function findDevice(model) {
  for (const file of fs.readdirSync(devicesDir).filter((f) => f.endsWith('.js'))) {
    let mod;
    try { mod = require(path.join(devicesDir, file)); } catch { continue; }
    for (const raw of mod.definitions || []) {
      const models = [raw.model, ...(raw.zigbeeModel || []), ...(raw.fingerprint || []).map((f) => f.modelID)].filter(Boolean);
      if (models.includes(model)) return raw;
    }
  }
  return undefined;
}

const raw = findDevice('SNZB-01P');
if (!raw) { console.error('SNZB-01P not found'); process.exit(1); }

const fragment = (raw.extend || []).find((e) => (e.exposes || []).some((x) => x.name === 'battery' || x.property === 'battery'));
if (!fragment) { console.error('battery fragment not found'); process.exit(1); }
const call = calls.find((c) => c.result === fragment);
const opts = call ? call.args : {};
const pctCfg = opts.percentageReportingConfig || { min: 3600, max: 7200, change: 0 };
const voltCfg = opts.voltageReportingConfig || { min: 3600, max: 7200, change: 0 };
const convert = fragment.fromZigbee[0].convert;

const golden = [];
for (const value of [200, 123, 255]) {
  const out = convert(raw, { data: { batteryPercentageRemaining: value } }, () => {}, {}, {});
  golden.push({ attr: 0x0021, raw: value, out });
}
for (const value of [30, 255]) {
  const out = convert(raw, { data: { batteryVoltage: value } }, () => {}, {}, {});
  golden.push({ attr: 0x0020, raw: value, out });
}

